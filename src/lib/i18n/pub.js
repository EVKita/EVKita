const DICTS = { id: ID, en: EN };

/** Nama cookie pilihan bahasa situs publik. */
export const PUB_COOKIE = "evkita_pub_lang";

export const PUB_DEFAULT = "id";

export function normalizePubLocale(value) {
  const s = String(value || "").toLowerCase().split(/[-_]/)[0];
  return DICTS[s] ? s : PUB_DEFAULT;
}

function interpolate(text, vars) {
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (whole, key) =>
    Object.prototype.hasOwnProperty.call(vars, key) ? String(vars[key]) : whole
  );
}

/** Terjemahkan satu kunci; jatuh ke Bahasa Indonesia kalau belum ada. */
export function pubT(locale, key, vars) {
  const dict = DICTS[normalizePubLocale(locale)] || ID;
  const text = dict[key] !== undefined ? dict[key] : ID[key];
  if (text === undefined) return key;
  return interpolate(text, vars);
}

/** Fungsi `t` yang sudah terikat ke satu bahasa. */
export function makePubT(locale) {
  const code = normalizePubLocale(locale);
  return (key, vars) => pubT(code, key, vars);
}
